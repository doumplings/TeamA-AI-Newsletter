def _pg_enum(py_enum: type[enum.Enum], name: str) -> SAEnum:
    return SAEnum(
        py_enum,
        name=name,
        create_type=False,
        values_callable=lambda e: [m.value for m in e],
    )


user_role_t = _pg_enum(UserRole, "user_role")
channel_type_t = _pg_enum(ChannelType, "channel_type")
source_type_t = _pg_enum(SourceType, "source_type")
