# PK/FK names generated by convention match the names written in schema.sql.
# UNIQUE, CHECK and index names are given explicitly on each table.
NAMING_CONVENTION = {
    "pk": "pk_%(table_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s",
}

TIMESTAMPTZ = TIMESTAMP(timezone=True)
HEX64 = CHAR(64)
MAX_VERIFICATION_ATTEMPTS = 3
MAX_DELIVERY_ATTEMPTS = 5
# ``last_error`` values written by ``DeliveryRepository.cancel_undeliverable``. The
# REQ-14 delivery-rate metric should exclude these, since no send was attempted.
CHANNEL_DELETED_ERROR = "channel deleted"
CHANNEL_DISABLED_ERROR = "channel disabled"


class Base(DeclarativeBase):
    """Declarative base for all AI Newsletter models."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    # Every datetime is timestamptz and every bytes column is bytea, so plain
    # ``Mapped[datetime]`` / ``Mapped[bytes]`` annotations need no explicit type.
    type_annotation_map = {datetime: TIMESTAMPTZ, bytes: BYTEA}


# Reusable column shapes for recurring NOT NULL + server default patterns.
CreatedAt = Annotated[datetime, mapped_column(server_default=func.now())]
DefaultTrue = Annotated[bool, mapped_column(server_default=text("true"))]
DefaultFalse = Annotated[bool, mapped_column(server_default=text("false"))]


def make_engine(url: str | None = None) -> Engine:
    """Create an engine from ``url`` or the ``DATABASE_URL`` environment variable."""
    return create_engine(url or os.environ["DATABASE_URL"], pool_pre_ping=True)


def make_session_factory(engine: Engine | None = None) -> sessionmaker[Session]:
    """Create a session factory bound to ``engine`` (default: ``make_engine()``)."""
    return sessionmaker(engine or make_engine(), expire_on_commit=False)


