class MatchRecord(NamedTuple):
    """Input row for ``NewsItemRepository.save_classification``."""

    rule_id: int
    field: MatchField
    contribution: Decimal


class _Repository:
    """Base for all repositories: wraps a caller-owned ``Session``.

    Repositories flush but never commit; the caller controls the transaction.
    """

    def __init__(self, db: Session) -> None:
        self.db = db


class UserRepository(_Repository):
    """Persistence for accounts and their subscriber profiles."""

    def create_subscriber(self, email: str, password_hash: str) -> User:
        """Insert a subscriber account and its profile in the caller's transaction."""
        user = User(email=email, password_hash=password_hash, role=UserRole.subscriber)
        user.profile = SubscriberProfile()
        self.db.add(user)
        self.db.flush()
        return user

    def get_by_email(self, email: str) -> User | None:
        """Case-insensitive lookup served by ``uq_users_email_lower``."""
        stmt = select(User).where(func.lower(User.email) == func.lower(email))
        return self.db.scalars(stmt).one_or_none()

    def touch_login(self, user_id: int) -> None:
        """Set ``last_login_at`` to the database's current time."""
        self.db.execute(
            update(User).where(User.user_id == user_id).values(last_login_at=func.now())
        )


class SessionRepository(_Repository):
    """Persistence for login sessions, keyed by the hashed cookie token."""

    def create(self, user_id: int, token_hash: str, ttl: timedelta) -> UserSession:
        """Insert a session expiring ``ttl`` after the database's current time."""
        stmt = (
            pg_insert(UserSession)
            .values(user_id=user_id, token_hash=token_hash, expires_at=func.now() + ttl)
            .returning(UserSession)
        )
        return self.db.scalars(stmt).one()

    def get_valid(self, token_hash: str) -> UserSession | None:
        """Return the session for ``token_hash`` if it has not expired."""
        stmt = select(UserSession).where(
            UserSession.token_hash == token_hash, UserSession.expires_at > func.now()
        )
        return self.db.scalars(stmt).one_or_none()

    def delete(self, token_hash: str) -> bool:
        """Delete one session; return whether it existed."""
        result = self.db.execute(delete(UserSession).where(UserSession.token_hash == token_hash))
        return result.rowcount > 0

    def purge_expired(self) -> int:
        """Delete all expired sessions; return how many were removed."""
        result = self.db.execute(delete(UserSession).where(UserSession.expires_at <= func.now()))
        return result.rowcount


class ChannelRepository(_Repository):
    """Persistence for delivery channels and their verification state."""

    def add(
        self,
        user_id: int,
        channel_type: ChannelType,
        contact_encrypted: bytes,
        contact_hash: str,
        min_importance: ImportanceLevel | None = None,
    ) -> ChannelConnection:
        """Insert an unverified channel for a subscriber."""
        channel = ChannelConnection(
            user_id=user_id,
            channel_type=channel_type,
            contact_encrypted=contact_encrypted,
            contact_hash=contact_hash,
            min_importance=min_importance,
        )
        self.db.add(channel)
        self.db.flush()
        return channel

    def get_by_contact(self, channel_type: ChannelType, contact_hash: str) -> ChannelConnection | None:
        """Find a channel by its keyed contact hash, e.g. an incoming Telegram chat ID (C5)."""
        stmt = select(ChannelConnection).where(
            ChannelConnection.channel_type == channel_type,
            ChannelConnection.contact_hash == contact_hash,
        )
        return self.db.scalars(stmt).one_or_none()

    def set_verification_code(self, channel_id: int, code_hash: str, ttl: timedelta) -> bool:
        """Store a new code hash, expiring after ``ttl``, and reset failed attempts."""
        result = self.db.execute(
            update(ChannelConnection)
            .where(ChannelConnection.channel_id == channel_id)
            .values(
                verification_code_hash=code_hash,
                code_expires_at=func.now() + ttl,
                failed_attempts=0,
            )
        )
        return result.rowcount > 0

    def record_failed_attempt(self, channel_id: int) -> int:
        """Increment ``failed_attempts`` (capped at 3); return attempts remaining."""
        stmt = (
            update(ChannelConnection)
            .where(
                ChannelConnection.channel_id == channel_id,
                ChannelConnection.failed_attempts < MAX_VERIFICATION_ATTEMPTS,
            )
            .values(failed_attempts=ChannelConnection.failed_attempts + 1)
            .returning(MAX_VERIFICATION_ATTEMPTS - ChannelConnection.failed_attempts)
        )
        remaining = self.db.scalars(stmt).one_or_none()
        return 0 if remaining is None else remaining

    def mark_verified(self, channel_id: int) -> bool:
        """Mark a channel verified now and clear its pending code."""
        result = self.db.execute(
            update(ChannelConnection)
            .where(ChannelConnection.channel_id == channel_id)
            .values(
                is_verified=True,
                verified_at=func.now(),
                verification_code_hash=None,
                code_expires_at=None,
                failed_attempts=0,
            )
        )
        return result.rowcount > 0


class SourceRepository(_Repository):
    """Persistence for scrape targets and their fetch state."""

    def active(self) -> Sequence[Source]:
        """Active sources, least recently checked first (never-checked first of all)."""
        stmt = (
            select(Source)
            .where(Source.is_active.is_(True))
            .order_by(Source.last_checked_at.asc().nulls_first())
        )
        return self.db.scalars(stmt).all()

    def record_success(
        self, source_id: int, etag: str | None, last_modified: str | None
    ) -> None:
        """Record a successful fetch and store its validators (on a 304, pass the old ones back)."""
        self.db.execute(
            update(Source)
            .where(Source.source_id == source_id)
            .values(
                etag=etag,
                last_modified=last_modified,
                last_checked_at=func.now(),
                last_success_at=func.now(),
                consecutive_failures=0,
                last_error=None,
            )
        )

    def record_failure(self, source_id: int, error: str) -> int:
        """Record a failed fetch; return the new ``consecutive_failures`` count."""
        stmt = (
            update(Source)
            .where(Source.source_id == source_id)
            .values(
                last_checked_at=func.now(),
                consecutive_failures=Source.consecutive_failures + 1,
                last_error=error,
            )
            .returning(Source.consecutive_failures)
        )
        return self.db.scalars(stmt).one()


class NewsItemRepository(_Repository):
    """Persistence for collected news items and their classification."""

    def insert_if_new(
        self,
        source_id: int,
        title: str,
        url: str,
        canonical_url: str,
        summary: str | None = None,
        body: str | None = None,
        published_at: datetime | None = None,
        duplicate_of: int | None = None,
    ) -> int | None:
        """Insert an item unless ``canonical_url`` exists; return the new id or None.

        C7: if ``duplicate_of`` names an item that is itself a duplicate, the
        link is redirected to that item's original, so chains never form. When
        a duplicate is inserted, the original's ``corroboration_count`` is
        incremented in the same statement batch.
        """
        if duplicate_of is not None:
            root = self.db.scalar(
                select(func.coalesce(NewsItem.duplicate_of, NewsItem.item_id))
                .where(NewsItem.item_id == duplicate_of)
                .with_for_update()
            )
            duplicate_of = root if root is not None else duplicate_of

        stmt = (
            pg_insert(NewsItem)
            .values(
                source_id=source_id,
                title=title,
                summary=summary,
                body=body,
                url=url,
                canonical_url=canonical_url,
                published_at=published_at,
                duplicate_of=duplicate_of,
            )
            .on_conflict_do_nothing(index_elements=[NewsItem.canonical_url])
            .returning(NewsItem.item_id)
        )
        item_id = self.db.scalars(stmt).one_or_none()

        if item_id is not None and duplicate_of is not None:
            self.db.execute(
                update(NewsItem)
                .where(NewsItem.item_id == duplicate_of)
                .values(corroboration_count=NewsItem.corroboration_count + 1)
            )
        return item_id

    def unclassified(self, limit: int) -> Sequence[NewsItem]:
        """Lock and return the oldest unclassified items (``ix_news_items_unclassified``).

        Rows held by another classifier are skipped, so keep the transaction open
        until ``save_classification`` has been called for each item.
        """
        stmt = (
            select(NewsItem)
            .where(NewsItem.classified_at.is_(None))
            .order_by(NewsItem.collected_at)
            .limit(limit)
            .with_for_update(skip_locked=True)
        )
        return self.db.scalars(stmt).all()

    def undispatched(self, limit: int) -> Sequence[NewsItem]:
        """Lock and return the oldest undispatched items (``ix_news_items_undispatched``).

        Rows held by another dispatcher are skipped, as in ``unclassified``.
        """
        stmt = (
            select(NewsItem)
            .where(NewsItem.classified_at.is_not(None), NewsItem.dispatched_at.is_(None))
            .order_by(NewsItem.classified_at)
            .limit(limit)
            .with_for_update(skip_locked=True)
        )
        return self.db.scalars(stmt).all()

    def save_classification(
        self,
        item_id: int,
        score: Decimal,
        level: ImportanceLevel,
        matches: Sequence[MatchRecord],
    ) -> None:
        """Replace the item's rule matches and set score, level and ``classified_at``."""
        self.db.execute(delete(RuleMatch).where(RuleMatch.item_id == item_id))
        if matches:
            self.db.execute(
                pg_insert(RuleMatch),
                [
                    {
                        "item_id": item_id,
                        "rule_id": m.rule_id,
                        "field": m.field,
                        "contribution": m.contribution,
                    }
                    for m in matches
                ],
            )
        self.db.execute(
            update(NewsItem)
            .where(NewsItem.item_id == item_id)
            .values(importance_score=score, importance_level=level, classified_at=func.now())
        )

    def candidates_for_duplicate(self, since: datetime) -> Sequence[NewsItem]:
        """Originals published (or, if undated, collected) at or after ``since``."""
        stmt = (
            select(NewsItem)
            .where(
                NewsItem.duplicate_of.is_(None),
                or_(
                    NewsItem.published_at >= since,
                    and_(NewsItem.published_at.is_(None), NewsItem.collected_at >= since),
                ),
            )
            .order_by(NewsItem.published_at.desc().nulls_last())
        )
        return self.db.scalars(stmt).all()


class DeliveryRepository(_Repository):
    """Persistence for the delivery queue."""

    def enqueue_for_item(self, item_id: int) -> int:
        """Queue the item for every eligible channel and stamp ``dispatched_at``.

        Duplicates (``duplicate_of IS NOT NULL``) get no deliveries, since the
        original already went out; they are still stamped so they leave the queue.

        Eligible: enabled and verified, effective threshold
        ``COALESCE(min_importance, default_threshold) <= importance_level``, and
        the owner follows the item's source (``follows_all`` or a
        ``followed_sources`` row). Returns the number of deliveries created.
        """
        cc, sp, ni, fs = ChannelConnection, SubscriberProfile, NewsItem, FollowedSource
        eligible = (
            select(ni.item_id, cc.channel_id)
            .select_from(cc)
            .join(sp, sp.user_id == cc.user_id)
            .join(ni, ni.item_id == item_id)
            .where(
                ni.duplicate_of.is_(None),
                cc.is_enabled.is_(True),
                cc.is_verified.is_(True),
                # A NULL (unclassified) level compares as NULL, so it matches nothing.
                func.coalesce(cc.min_importance, sp.default_threshold) <= ni.importance_level,
                or_(
                    sp.follows_all.is_(True),
                    exists().where(fs.user_id == sp.user_id, fs.source_id == ni.source_id),
                ),
            )
        )
        stmt = (
            pg_insert(Delivery)
            .from_select(["item_id", "channel_id"], eligible)
            .on_conflict_do_nothing(constraint="uq_deliveries_item_channel")
            .returning(Delivery.delivery_id)
        )
        created = len(self.db.scalars(stmt).all())
        self.db.execute(
            update(NewsItem)
            .where(
                NewsItem.item_id == item_id,
                NewsItem.classified_at.is_not(None),
                NewsItem.dispatched_at.is_(None),
            )
            .values(dispatched_at=func.now())
        )
        return created

    def due(self, limit: int) -> Sequence[Delivery]:
        """Lock and return deliveries ready to (re)send, skipping rows other workers hold.

        Deliveries to deleted or disabled channels are left for
        ``cancel_undeliverable``. Only the delivery rows are locked, not the channels.
        """
        stmt = (
            select(Delivery)
            .join(ChannelConnection, ChannelConnection.channel_id == Delivery.channel_id)
            .where(
                Delivery.status.in_([DeliveryStatus.queued, DeliveryStatus.failed]),
                Delivery.next_attempt_at <= func.now(),
                ChannelConnection.is_enabled.is_(True),
            )
            .order_by(Delivery.next_attempt_at)
            .limit(limit)
            .with_for_update(skip_locked=True, of=Delivery)
        )
        return self.db.scalars(stmt).all()

    def cancel_undeliverable(self) -> int:
        """Move pending deliveries whose channel is deleted or disabled to ``permanent_failure``.

        ``last_error`` is set to ``CHANNEL_DELETED_ERROR`` or ``CHANNEL_DISABLED_ERROR``
        so the delivery-rate metric can tell these apart from real send failures.
        ``attempts`` is left unchanged. Returns the number of deliveries cancelled.
        """
        channel_disabled = exists().where(
            ChannelConnection.channel_id == Delivery.channel_id,
            ChannelConnection.is_enabled.is_(False),
        )
        result = self.db.execute(
            update(Delivery)
            .where(
                Delivery.status.in_([DeliveryStatus.queued, DeliveryStatus.failed]),
                or_(Delivery.channel_id.is_(None), channel_disabled),
            )
            .values(
                status=DeliveryStatus.permanent_failure,
                last_error=case(
                    (Delivery.channel_id.is_(None), CHANNEL_DELETED_ERROR),
                    else_=CHANNEL_DISABLED_ERROR,
                ),
            )
        )
        return result.rowcount

    def mark_sent(self, delivery_id: int) -> None:
        """Record a successful send."""
        self.db.execute(
            update(Delivery)
            .where(Delivery.delivery_id == delivery_id)
            .values(
                status=DeliveryStatus.sent,
                sent_at=func.now(),
                attempts=Delivery.attempts + 1,
                last_error=None,
            )
        )

    def mark_failed(self, delivery_id: int, error: str, backoff: timedelta) -> DeliveryStatus:
        """Record a failed send; becomes ``permanent_failure`` on the 5th attempt."""
        new_attempts = Delivery.attempts + 1
        stmt = (
            update(Delivery)
            .where(Delivery.delivery_id == delivery_id)
            .values(
                attempts=new_attempts,
                status=cast(
                    case(
                        (new_attempts >= MAX_DELIVERY_ATTEMPTS, DeliveryStatus.permanent_failure.value),
                        else_=DeliveryStatus.failed.value,
                    ),
                    delivery_status_t,
                ),
                last_error=error,
                next_attempt_at=func.now() + backoff,
            )
            .returning(Delivery.status)
        )
        return self.db.scalars(stmt).one()


class CycleRunRepository(_Repository):
    """Persistence for the pipeline operations log."""

    def start(self, cycle_type: CycleType) -> int:
        """Open a run record and return its ``run_id``."""
        stmt = pg_insert(CycleRun).values(cycle_type=cycle_type).returning(CycleRun.run_id)
        return self.db.scalars(stmt).one()

    def finish(
        self, run_id: int, processed: int, failures: int, notes: str | None = None
    ) -> None:
        """Close a run record with its counters."""
        self.db.execute(
            update(CycleRun)
            .where(CycleRun.run_id == run_id)
            .values(
                finished_at=func.now(),
                items_processed=processed,
                failures=failures,
                notes=notes,
            )
        )
